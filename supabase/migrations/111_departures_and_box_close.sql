-- 111: boxes close, are uniquely named, and fly on real departures (site brief, Fix 9).
--
-- Until now a box only ever opened: 102 boxes on prod, all `open`, most past
-- their cutoff, 46 of them called "Box 1". Departures were one weekday per
-- region (Friday) computed on the fly, so the dashboard promised "Ships Fri"
-- for boxes nothing would ever ship.
--
-- * `flight_departures`: the scheduled flights. Delta Cargo, JFK → Accra, every
--   Wednesday and Friday (regions.departure_weekdays), generated three weeks
--   ahead by `run_box_schedule()`. A box rides one departure (`departure_id`).
--   The Delta air waybill for a departure lives here too (`awb`, Fix 12).
-- * `consolidation_boxes.code`: BX-1001, BX-1002… system-generated and unique.
-- * Closing: at cutoff, at capacity, or by staff. A closed box keeps its
--   departure and contents; the bag packer only ever reuses `open` boxes.
-- * Housekeeping: a box past its cutoff with nothing paid in it either follows
--   its open bag to the next departure or, when empty, is archived.

BEGIN;

-- ── Departure schedule per region ───────────────────────────────────────────
ALTER TABLE regions
  ADD COLUMN IF NOT EXISTS departure_weekdays SMALLINT[],
  ADD COLUMN IF NOT EXISTS departure_carrier TEXT,
  ADD COLUMN IF NOT EXISTS departure_origin TEXT,
  ADD COLUMN IF NOT EXISTS departure_destination TEXT,
  -- The departure's clock time in UTC. 00:00 keeps the day-level schedule the
  -- bag has always used until the real flight time is set.
  ADD COLUMN IF NOT EXISTS departure_time_utc TIME NOT NULL DEFAULT '00:00';

COMMENT ON COLUMN regions.departure_weekdays IS
  '111: days of the week a consolidated shipment departs (0 = Sunday … 6 = Saturday). NULL = no schedule; boxes stay unscheduled.';

UPDATE regions
SET departure_weekdays = ARRAY[3, 5]::SMALLINT[],
    departure_carrier = 'Delta Cargo',
    departure_origin = 'JFK',
    departure_destination = 'ACC'
WHERE code = 'USA' AND departure_weekdays IS NULL;

CREATE TABLE IF NOT EXISTS flight_departures (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  region_code   TEXT NOT NULL REFERENCES regions(code),
  carrier       TEXT NOT NULL,
  origin        TEXT NOT NULL,
  destination   TEXT NOT NULL,
  departs_on    DATE NOT NULL,
  departs_at    TIMESTAMPTZ NOT NULL,
  cutoff_at     TIMESTAMPTZ NOT NULL,
  status        TEXT NOT NULL DEFAULT 'scheduled'
    CHECK (status IN ('scheduled', 'closed', 'departed', 'cancelled')),
  -- Fix 12: the Delta Cargo air waybill once the shipment is booked.
  awb           TEXT,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT flight_departures_one_per_day UNIQUE (region_code, departs_on),
  CHECK (cutoff_at <= departs_at)
);

COMMENT ON TABLE flight_departures IS
  '111: scheduled consolidated departures (Delta Cargo JFK → ACC, Wed + Fri). Generated by run_box_schedule(); boxes ride one (consolidation_boxes.departure_id).';

CREATE INDEX IF NOT EXISTS idx_flight_departures_next
  ON flight_departures (region_code, cutoff_at) WHERE status = 'scheduled';

ALTER TABLE flight_departures ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON flight_departures TO anon, authenticated;
GRANT ALL ON flight_departures TO service_role;
-- A flight schedule is public information: the dashboard and /track show it.
CREATE POLICY "flight_departures public read"
  ON flight_departures FOR SELECT TO anon, authenticated USING (true);

-- ── Boxes: unique codes, departures, closing, archiving ──────────────────────
CREATE SEQUENCE IF NOT EXISTS consolidation_box_code_seq START 1001;

ALTER TABLE consolidation_boxes
  ADD COLUMN IF NOT EXISTS code TEXT,
  ADD COLUMN IF NOT EXISTS departure_id UUID REFERENCES flight_departures(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS closed_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS closed_reason TEXT CHECK (closed_reason IN ('cutoff', 'capacity', 'staff')),
  ADD COLUMN IF NOT EXISTS closed_by UUID REFERENCES profiles(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS archived_at TIMESTAMPTZ;

-- Every existing box gets its code in the order it was opened.
WITH ordered AS (
  SELECT id FROM consolidation_boxes WHERE code IS NULL ORDER BY created_at, id
)
UPDATE consolidation_boxes b
SET code = 'BX-' || nextval('consolidation_box_code_seq')
FROM ordered
WHERE b.id = ordered.id;

ALTER TABLE consolidation_boxes
  ALTER COLUMN code SET DEFAULT ('BX-' || nextval('consolidation_box_code_seq')),
  ALTER COLUMN code SET NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uniq_consolidation_boxes_code ON consolidation_boxes (code);

ALTER TABLE consolidation_boxes DROP CONSTRAINT IF EXISTS consolidation_boxes_status_check;
ALTER TABLE consolidation_boxes ADD CONSTRAINT consolidation_boxes_status_check
  CHECK (status IN ('open', 'closed', 'in_transit', 'landed', 'archived'));

COMMENT ON COLUMN consolidation_boxes.code IS '111: the box''s name everywhere (admin, dashboard, warehouse). System-generated, unique.';
COMMENT ON COLUMN consolidation_boxes.closed_reason IS '111: why it closed: cutoff (the departure''s cutoff passed), capacity (full), staff (closed by hand).';

-- ── The schedule job ─────────────────────────────────────────────────────────
-- Paid-onward orders are what a box physically carries; anything earlier is a plan.
CREATE OR REPLACE FUNCTION run_box_schedule()
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_created  INT := 0;
  v_capacity INT := 0;
  v_cutoff   INT := 0;
  v_rolled   INT := 0;
  v_archived INT := 0;
BEGIN
  -- 1. Departures three weeks ahead, one per scheduled weekday.
  WITH days AS (
    SELECT r.code, r.departure_carrier, r.departure_origin, r.departure_destination,
           r.departure_cutoff_hours, r.departure_time_utc, d::date AS day
    FROM regions r
    CROSS JOIN generate_series(current_date, current_date + 21, interval '1 day') d
    WHERE r.departure_weekdays IS NOT NULL
      AND r.departure_carrier IS NOT NULL
      AND extract(dow FROM d)::INT = ANY (r.departure_weekdays)
  ), ins AS (
    INSERT INTO flight_departures (region_code, carrier, origin, destination, departs_on, departs_at, cutoff_at)
    SELECT code, departure_carrier, coalesce(departure_origin, ''), coalesce(departure_destination, ''), day,
           (day + departure_time_utc) AT TIME ZONE 'UTC',
           ((day + departure_time_utc) AT TIME ZONE 'UTC') - make_interval(hours => coalesce(departure_cutoff_hours, 24))
    FROM days
    WHERE ((day + departure_time_utc) AT TIME ZONE 'UTC') - make_interval(hours => coalesce(departure_cutoff_hours, 24)) > now()
    ON CONFLICT (region_code, departs_on) DO NOTHING
    RETURNING 1
  )
  SELECT count(*) INTO v_created FROM ins;

  UPDATE flight_departures SET status = 'departed', updated_at = now()
  WHERE status IN ('scheduled', 'closed') AND departs_at <= now();
  UPDATE flight_departures SET status = 'closed', updated_at = now()
  WHERE status = 'scheduled' AND cutoff_at <= now();

  -- 2. Capacity: an open box whose paid contents reach its capacity closes.
  WITH full_boxes AS (
    SELECT b.id
    FROM consolidation_boxes b
    JOIN orders o ON o.consolidation_box_id = b.id
      AND o.status IN ('paid', 'processing', 'in_transit', 'delivered', 'completed')
    WHERE b.status = 'open'
    GROUP BY b.id, b.capacity_lbs
    HAVING sum(coalesce(nullif(o.pricing->>'weight_lbs', '')::NUMERIC, 0) * greatest(o.quantity, 1)) >= b.capacity_lbs
  ), upd AS (
    UPDATE consolidation_boxes b
    SET status = 'closed', closed_at = now(), closed_reason = 'capacity', updated_at = now()
    FROM full_boxes f WHERE b.id = f.id
    RETURNING 1
  )
  SELECT count(*) INTO v_capacity FROM upd;

  -- 3. Cutoff: an open box with paid contents whose cutoff has passed closes on its departure.
  WITH upd AS (
    UPDATE consolidation_boxes b
    SET status = 'closed', closed_at = now(), closed_reason = 'cutoff', updated_at = now()
    WHERE b.status = 'open'
      AND b.cutoff_at IS NOT NULL AND b.cutoff_at <= now()
      AND EXISTS (
        SELECT 1 FROM orders o
        WHERE o.consolidation_box_id = b.id
          AND o.status IN ('paid', 'processing', 'in_transit', 'delivered', 'completed')
      )
    RETURNING 1
  )
  SELECT count(*) INTO v_cutoff FROM upd;

  -- 4. A plan that missed its cutoff (an open bag, or an unpaid checkout), or a
  --    box that was never scheduled, follows the region's next departure. A
  --    region with none leaves it unscheduled.
  WITH stale AS (
    SELECT b.id,
           (SELECT d.id FROM flight_departures d
            WHERE d.region_code = b.region_code AND d.status = 'scheduled' AND d.cutoff_at > now()
            ORDER BY d.departs_at LIMIT 1) AS next_departure
    FROM consolidation_boxes b
    WHERE b.status = 'open'
      AND (b.cutoff_at IS NULL OR b.cutoff_at <= now())
      AND (
        EXISTS (SELECT 1 FROM cart_items ci JOIN carts c ON c.id = ci.cart_id
                WHERE ci.consolidation_box_id = b.id AND c.status = 'open')
        OR EXISTS (SELECT 1 FROM orders o WHERE o.consolidation_box_id = b.id AND o.status = 'pending_payment')
        -- Never scheduled (no cutoff at all) but carrying paid orders: it rides the next flight.
        OR (b.cutoff_at IS NULL AND EXISTS (
              SELECT 1 FROM orders o WHERE o.consolidation_box_id = b.id
                AND o.status IN ('paid', 'processing', 'in_transit', 'delivered', 'completed')))
      )
  ), upd AS (
    UPDATE consolidation_boxes b
    SET departure_id = d.id, departs_at = d.departs_at, cutoff_at = d.cutoff_at, updated_at = now()
    FROM stale s JOIN flight_departures d ON d.id = s.next_departure
    WHERE b.id = s.id
    RETURNING 1
  )
  SELECT count(*) INTO v_rolled FROM upd;

  -- 4b. A box still ahead of its cutoff but with no departure (opened before
  --     111, or before the schedule existed) rides the flight that day.
  UPDATE consolidation_boxes b
  SET departure_id = d.id, departs_at = d.departs_at, cutoff_at = d.cutoff_at, updated_at = now()
  FROM flight_departures d
  WHERE b.status = 'open' AND b.departure_id IS NULL
    AND b.departs_at IS NOT NULL AND b.cutoff_at > now()
    AND d.region_code = b.region_code AND d.status = 'scheduled'
    AND d.departs_on = (b.departs_at AT TIME ZONE 'UTC')::date;

  -- 5. Empty: nothing paid, nothing pending, no open bag line, past its cutoff
  --    (or a day old with no schedule): archived, never left open.
  WITH upd AS (
    UPDATE consolidation_boxes b
    SET status = 'archived', archived_at = now(), updated_at = now()
    WHERE b.status = 'open'
      AND (b.cutoff_at <= now() OR (b.cutoff_at IS NULL AND b.created_at < now() - interval '1 day'))
      AND NOT EXISTS (
        SELECT 1 FROM orders o
        WHERE o.consolidation_box_id = b.id AND o.status <> 'cancelled'
      )
      AND NOT EXISTS (
        SELECT 1 FROM cart_items ci JOIN carts c ON c.id = ci.cart_id
        WHERE ci.consolidation_box_id = b.id AND c.status = 'open'
      )
    RETURNING 1
  )
  SELECT count(*) INTO v_archived FROM upd;

  RETURN jsonb_build_object(
    'departures_created', v_created,
    'closed_capacity', v_capacity,
    'closed_cutoff', v_cutoff,
    'rolled_forward', v_rolled,
    'archived', v_archived
  );
END;
$$;

REVOKE ALL ON FUNCTION run_box_schedule() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION run_box_schedule() TO service_role;

DO $$
BEGIN
  PERFORM cron.unschedule('box-schedule') WHERE EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'box-schedule');
  PERFORM cron.schedule('box-schedule', '*/15 * * * *', 'SELECT run_box_schedule();');
END $$;

COMMIT;
